"""Compact Markdown and CSV evidence writer."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd


def _markdown_table(frame: pd.DataFrame, columns: list[str] | None = None) -> str:
    if frame.empty:
        return "_No rows._"
    view = frame[columns] if columns else frame
    return view.to_markdown(index=False, floatfmt=".6g")


def write_outputs(
    output_dir: Path,
    distribution: pd.DataFrame,
    distribution_by_year: pd.DataFrame,
    by_secid: pd.DataFrame,
    temporal_yearly: pd.DataFrame,
    temporal_detail: dict,
    consistency: pd.DataFrame,
    future_summary: pd.DataFrame,
    future_by_year: pd.DataFrame,
    future_by_secid: pd.DataFrame,
    metadata: dict,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    distribution.to_csv(output_dir / "distribution_summary.csv", index=False)
    distribution_by_year.to_csv(output_dir / "distribution_by_year.csv", index=False)
    by_secid.to_csv(output_dir / "instrument_coverage_summary.csv", index=False)
    temporal_yearly.to_csv(output_dir / "temporal_by_year.csv", index=False)
    consistency.to_csv(output_dir / "consistency_checks.csv", index=False)
    future_summary.to_csv(output_dir / "future_price_summary.csv", index=False)
    future_by_year.to_csv(output_dir / "future_price_by_year.csv", index=False)
    future_by_secid.to_csv(output_dir / "future_price_by_secid.csv", index=False)
    (output_dir / "eda_metadata.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2, default=str),
        encoding="utf-8",
    )

    report = f"""# EDA Report: PIT TOP50 Panel

> Status: generated by the user locally. This report is descriptive data analysis, not target selection or model evaluation.

## Scope and provenance

- Panel: `{metadata['panel_path']}`
- Adjusted history: `{metadata['adjusted_db_path']}`
- Data dates: {metadata['panel_start']} to {metadata['panel_end']}
- Panel rows: {metadata['panel_rows']:,}; SECIDs: {metadata['secids']:,}; dates: {metadata['dates']:,}
- Market calendar sessions: {metadata['calendar_sessions']:,}
- Price board rule: complete OHLC row first, then TQBR, then EQBR.
- No forward-fill, no synthetic bars, no outlier deletion, no source-data mutation.
- Future-price horizons are descriptive endpoints at +1, +5 and +20 market sessions. They do not define a prediction target or model task.
- `numtrades` is not analyzed.

## 1. Temporal structure and coverage

{_markdown_table(temporal_yearly)}

### Overall coverage and membership dynamics

{_markdown_table(pd.DataFrame([temporal_detail['summary']]))}

## 2. Distributions of observed variables

Market variables are summarized on rows with `bar_available=1`. Membership variables are summarized on all PIT membership rows. Extreme values are retained.

{_markdown_table(distribution)}

### Per-year distribution summaries

See `distribution_by_year.csv` for full aggregate detail.

{_markdown_table(distribution_by_year.head(24))}

### Instrument-level coverage and activity

{_markdown_table(by_secid.sort_values('membership_rows', ascending=False).head(15))}

## 3. Internal consistency diagnostics

These are descriptive flags only. No observation is automatically corrected or removed.

{_markdown_table(consistency)}

## 4. Future adjusted-close behavior

For each PIT TOP50 observation with a valid current bar, compare adjusted Close at t with adjusted Close at t+h, where h is a number of market-calendar sessions. Missing endpoints remain unavailable; sessions are not bridged. Both absolute price change and scale-relative returns are reported.

{_markdown_table(future_summary)}

### By-year behavior

{_markdown_table(future_by_year.head(36))}

Per-instrument results are in `future_price_by_secid.csv`.

## Interpretation guardrails

- This report does not select a target, prediction horizon, model family, feature, or trading rule.
- The 1/5/20-session horizons are descriptive comparison points only.
- Absolute price changes are not cross-instrument comparable because price scales differ; simple and log returns provide scale-relative views.
- Return distributions can be affected by changing PIT membership, missing endpoints, corporate actions, and instrument heterogeneity.
- Positive/negative/zero shares describe realized outcomes in this sample; they are not forecasts.
- No IC, feature-target association, model fitting, walk-forward evaluation, or portfolio metric is computed.

## Files

- `eda_metadata.json`: run provenance and aggregate counts.
- `distribution_summary.csv`, `distribution_by_year.csv`.
- `instrument_coverage_summary.csv`, `temporal_by_year.csv`.
- `consistency_checks.csv`.
- `future_price_summary.csv`, `future_price_by_year.csv`, `future_price_by_secid.csv`.
"""
    (output_dir / "EDA_REPORT.md").write_text(report, encoding="utf-8")
